/** モードの一覧。zod（schema.ts）からも読むので、依存を持たない側に置く */
export const MODE_IDS = ['standard', 'brink', 'party'] as const;
export type ModeId = (typeof MODE_IDS)[number];

export interface ModeConfig {
  id: ModeId;
  lives: number;
  sections: number;
  roomsPerSection: number;
  slotsBySection: readonly number[];
  /** 正直者をただ一人にする。その一人だけが正解を正確に知っている */
  loneHonest: boolean;
  /**
   * 全員挑戦者。助言者ではなく、同じ部屋を歩く仲間として扱う。
   * 仲間も選び、死ぬ。挑戦者自身にも部分的な情報が配られる。
   */
  allChallengers?: boolean;
  /** 全員挑戦者のとき、挑戦者自身が正解を何択まで絞れているか */
  ownCandidates?: number;
  /**
   * 死んで区画をやり直すとき、顔ぶれと記録を残すか。
   *
   * 通常は残さない。残すと死ぬたびに記録が積み上がり、
   * やり直すほど読みが楽になって難度の曲線が逆を向く
   * （実際に「正14 嘘1」と「正3 嘘12」に割れきって作業になっていた）。
   *
   * 崖っぷちは残す。**記録が唯一の道具**だからで、
   * 5部屋しかない区画で死ぬたびに白紙に戻すと、
   * ほとんどの部屋を信用0.50の当てずっぽうで打つことになる。
   */
  keepCastOnDeath?: boolean;
  /**
   * 「黙らせる」が使えるか。
   *
   * 崖っぷちだけ。あちらは正直者がただ一人なので、
   * 一人確定させるだけで読みが大きく動く（実測 51%→70%）。
   *
   * 通常モードでは効かない。発言枠8で嘘つき3人だと、
   * 一人黙らせても集計の読みはほとんど動かない（81.2%→80.9%）。
   * 当たり率も34%で、当てずっぽう（3/8=38%）と変わらない。
   * **効かないうえに外すと時間が減る**ので、押すほど損をする罠になっていた。
   */
  canSilence?: boolean;
  /**
   * 嘘つきが本当のことを言う率。
   *
   * **いまは段取り（casting.ts の liarHonestyAt）が本線で、ここは控え。**
   * 本体（ai-advisors / party-engine）は「区画のどこで裏切るか」を
   * 人ごとに決めて渡すので、この率は使わない。
   * 段取りを渡さない呼び出し（昔の測定道具など）だけがここを見る。
   * モードごとに変えていた意味は、いまは段取りの側に無い。要整理。
   */
  liarHonesty: number;
  /** 嘘つきが迷ったふりをする率 */
  liarMimic: number;
  /**
   * 区画ごとの部屋数。無ければ roomsPerSection を全区画に使う。
   * 奥の区画を短くするために入れてある（RUN.roomsBySection の説明を見よ）
   */
  roomsBySection?: readonly number[];
  /**
   * 人を指す率（指す理由があるときに実際に指す割合）。
   *
   * 0 だと助言は全部「扉について」になり、8人が扉の名前しか言えないので
   * **会話が起きない。** 一周書き出して読んだら、どの部屋でも挑戦者が
   * やっていたのは「どの名前が何回出たか」の集計だった。
   *
   * 0.25 は測って決めた（tools/rubric.mjs を指す率で振った）。
   *   崖っぷち  読める打ち手 72.0% → 77.2%、腕の差 10.0→11.5pt
   *   0.35 まで上げると最良の打ち手が一つに固まる（最良差 6.6pt で落ちる）
   *   通常     +0.5pt 程度。深みはほぼ変わらないが、場が喋るようになる
   */
  nameCall: number;
}

