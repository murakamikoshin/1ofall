import type { Pen } from './style';

/**
 * 題材ごとの形。**部屋の5〜6枚は同じ物に見える**ようにする。
 *
 * 仮絵は8つの族（扉・器・手に持つもの…）に96題材を押し込んでいたので、
 * 鍵の部屋と銭の部屋が同じ絵になっていた。ここは題材ごとに形を持つ。
 *
 *   base    部屋の全枚数で共通の形（扉の部屋なら全部が扉）
 *   detail  既定の内側の印。「取手のない」「目のない」で消える
 *   marks   形容も物の名前も当たらないときだけ使う差分
 *
 * 描き込みの量は base＋多くて二つに抑える。豪華な絵があると
 * 「それが正解」という手掛かりになる（規約 §5 の最重要項目）。
 */
export interface Motif {
  base(p: Pen): string;
  detail?(p: Pen): string;
  marks?: ((p: Pen) => string)[];
  /**
   * 札の名前から形を引いてよい題材か。
   *
   * 「何を置いていく：帳面／銭／面／縄／名前」のように**選択肢が別々の物**の
   * 部屋だけ立てる。既定は立てない——「澄んだ水」を水の形で描いてしまうと、
   * 器の部屋（どれを空ける）に波が並ぶ。器の部屋の主役は器のほうなので。
   */
  nouns?: boolean;
}

function motif(
  base: (p: Pen) => string,
  detail?: (p: Pen) => string,
  marks: ((p: Pen) => string)[] = [],
): Motif {
  return detail ? { base, detail, marks } : { base, marks };
}

